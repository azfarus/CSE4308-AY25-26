/* * Lab 8 Data Generator (PostgreSQL Version)
 * Usage: \i lab8_data.sql
 */

-- 1. CLEANUP
DROP TABLE IF EXISTS TRANSACTIONS;
DROP TABLE IF EXISTS ACCOUNT;

-- 2. CREATE TABLES
CREATE TABLE ACCOUNT (
    A_ID INT PRIMARY KEY
);

CREATE TABLE TRANSACTIONS (
    T_ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Auto-increment
    DTM TIMESTAMP,
    A_ID INT,
    AMOUNT DECIMAL(15,2),
    TYPE INT, -- 0 for Credit, 1 for Debit (Matches Lab Manual)
    FOREIGN KEY (A_ID) REFERENCES ACCOUNT(A_ID)
);

-- 3. INSERT ACCOUNTS (Generates 100 Accounts)
INSERT INTO ACCOUNT (A_ID)
SELECT generate_series(1, 100);

-- 4. INSERT TRANSACTIONS (Generates ~1000 random transactions)
-- This query creates random data to satisfy Lab 8 tasks (CIP/VIP/Dates in 2021)
INSERT INTO TRANSACTIONS (DTM, A_ID, AMOUNT, TYPE)
SELECT
    -- Random Timestamp between Jan 1, 2020 and Dec 31, 2022
    timestamp '2020-01-01' + 
    random() * (timestamp '2022-12-31' - timestamp '2020-01-01'),
    
    -- Random Account ID (1 to 100)
    floor(random() * 100 + 1)::int,
    
    -- Random Amount (10,000 to 1,000,000 to hit CIP/VIP thresholds)
    (random() * 990000 + 10000)::decimal(15,2),
    
    -- Random Type (0 or 1)
    floor(random() * 2)::int
FROM generate_series(1, 1000); 

-- 5. COMMIT
COMMIT;

-- 6. VERIFICATION
SELECT 'Accounts Created' as Metric, COUNT(*) as Value FROM ACCOUNT
UNION ALL
SELECT 'Transactions Created', COUNT(*) FROM TRANSACTIONS;